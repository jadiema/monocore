#!/usr/bin/env python3
"""Builds the game-data sources of the port from your own copy of the game.

usage: python3 tools/prepare.py l-aigle-d-or_mo5.sd l-aigle-d-or_win.exe
  - the .sd disk image (SDDRIVE) gives the RAM image $2100-$9FFF loaded by AIGLE.JEU
    (127 sectors from track 2, sector 8): -> aigle_image.c, then aigle_code.c (translated code)
  - the DCMOTO executable gives the MO5 character set (from its MO5 ROM): -> mo5font.c, and the
    title sequence of its cassette image (BIN.BIN, DES.BIN): -> intro_data.c
These files come from the original game and ROM: keep them out of any public repository.
"""
import os, subprocess, sys
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
sd = open(sys.argv[1], 'rb').read()
sec = lambda t, s: sd[(t * 16 + s - 1) * 512:(t * 16 + s - 1) * 512 + 256]
img = bytearray(); t, s = 2, 7
while len(img) < 0x7F00:
    s += 1
    if s == 17: t, s = t + 1, 1
    img += sec(t, s)
open(os.path.join(root, 'aigle_mem.bin'), 'wb').write(img)
def c_array(name, data, comment, path):
    rows = ',\n'.join(', '.join('0x%02X' % x for x in data[i:i + 16]) for i in range(0, len(data), 16))
    open(path, 'w').write('// %s\n#include <stdint.h>\nconst uint8_t %s[%d] = {\n%s\n};\n' % (comment, name, len(data), rows))
c_array('aigle_image', img, "RAM image $2100-$9FFF of L'Aigle d'Or (generated by tools/prepare.py)",
        os.path.join(root, 'aigle_image.c'))
entries = '4390 4393 4399 43A2 43AB 43B4 43BD 43C6 43CF 43D8 43E1 43EA 43F3 43FC 4405 58F7 5900 5946 5986 59CC 5A0C 5A28 5A4D 5A96 5AD9 55D0'.split()
subprocess.check_call([sys.executable, os.path.join(here, 'recomp6809.py'), os.path.join(root, 'aigle_mem.bin'),
                       '2100', os.path.join(root, 'aigle_code.c')] + entries, cwd=here)
if len(sys.argv) > 2:
    exe = open(sys.argv[2], 'rb').read()
    if exe[:2] == b'MZ' and b'UPX' in exe[:1024]:
        subprocess.check_call(['upx', '-d', '-q', '-o', '/tmp/dcmoto_unpacked.exe', sys.argv[2]])
        exe = open('/tmp/dcmoto_unpacked.exe', 'rb').read(); os.remove('/tmp/dcmoto_unpacked.exe')
    base = exe.find(b'\x00\x3c\x42\x40\x40\x42\x3c\x00')       # 'C', rows stored bottom to top
    font = bytearray()
    for c in range(0x20, 0x80):
        g = exe[base + 8 * (c - 0x43):base + 8 * (c - 0x43) + 8]; font += bytes(reversed(g))
    # the cassette image embedded in DCMOTO: DES.BIN ($9204) and BIN.BIN ($5000) of the title sequence
    k = exe.find(b'\x3c\x5a\x00')
    while k >= 0 and exe[k + 4:k + 12] != b'AIGLE   ': k = exe.find(b'\x3c\x5a\x00', k + 1)
    files, cur, i = {}, None, k
    while 0 <= i < len(exe) - 4 and len(files) < 5:
        if exe[i] == 0x3C and exe[i + 1] == 0x5A:
            t, n = exe[i + 2], exe[i + 3] or 256
            body = exe[i + 4:i + 2 + n]
            if t == 0: cur = body[:8].decode('latin1').strip() + '.' + body[8:11].decode('latin1'); files[cur] = bytearray()
            elif t == 1 and cur: files[cur] += body
            elif t == 0xFF and cur == 'BIN.BIN': break
            i += 2 + n + 1 if n > 2 else 4
        else: i += 1
    des, binf = files['DES.BIN'], files['BIN.BIN']
    assert des[1:5] == b'\x0d\xfc\x92\x04' and binf[1:5] == b'\x0c\x01\x50\x00', 'cassette image not found'
    rows = lambda d: ',\n'.join(', '.join('0x%02X' % x for x in d[i:i + 16]) for i in range(0, len(d), 16))
    open(os.path.join(root, 'intro_data.c'), 'w').write(
        '// Title sequence of the cassette version: BIN.BIN ($5000) and DES.BIN ($9204) (tools/prepare.py)\n'
        '#include <stdint.h>\nconst uint8_t intro_bin[0xC01] = {\n%s\n};\nconst uint8_t intro_des[0xDFC] = {\n%s\n};\n'
        % (rows(binf[5:5 + 0xC01]), rows(des[5:5 + 0xDFC])))
    c_array('mo5_font', font, 'MO5 character set 0x20-0x7F (generated by tools/prepare.py)', os.path.join(root, 'mo5font.c'))
print('ok: aigle_image.c, aigle_code.c' + (', mo5font.c, intro_data.c' if len(sys.argv) > 2 else ''))
